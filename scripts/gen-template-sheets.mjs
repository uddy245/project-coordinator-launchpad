#!/usr/bin/env node
/**
 * Regenerate src/lib/lessons/template-sheets.ts — one line per sheet of each
 * STARTER workbook in public/templates, shown on the Workbook tab ("what goes
 * in each sheet"). Review the output; hand-edit wording if needed.
 *
 *   node scripts/gen-template-sheets.mjs
 */
import { readdirSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import XLSX from "xlsx";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = resolve(ROOT, "public/templates");
const files = readdirSync(DIR).filter((f) => f.endsWith(".xlsx") && !/_sample_|_example/.test(f));

// Enough of the sheet's instruction line to be useful on its own: whole
// sentences until at least ~40 characters, capped around 170.
const firstSentence = (s) => {
  const t = String(s).replace(/\s+/g, " ").trim();
  const sentences = t.match(/[^.!?]+[.!?]+(\s|$)|[^.!?]+$/g) ?? [t];
  let out = "";
  for (const sentence of sentences) {
    const next = (out + " " + sentence.trim()).trim();
    if (out && (out.length >= 40 || next.length > 170)) break;
    out = next;
  }
  return out.slice(0, 180);
};

const out = {};
for (const f of files.sort()) {
  const wb = XLSX.readFile(resolve(DIR, f));
  out[`/templates/${f}`] = wb.SheetNames.map((sheet) => {
    const rows = XLSX.utils
      .sheet_to_json(wb.Sheets[sheet], { header: 1, blankrows: false })
      .map((r) => r.filter((c) => c !== null && c !== undefined && String(c).trim() !== ""));
    let what;
    if (/^instructions?$/i.test(sheet)) {
      what = "Field-by-field guide to what goes in each column — read this first.";
    } else if (rows[0] && rows[0].length >= 4) {
      what = `One row per entry. Columns: ${rows[0].join(", ")}.`;
    } else if (rows[2] && rows[2].length) {
      what = firstSentence(rows[2].join(" "));
    } else {
      what = rows[1] ? firstSentence(rows[1].join(" ")) : "";
    }
    return { sheet, what };
  });
}

const body = `// GENERATED by scripts/gen-template-sheets.mjs — one line per sheet of each
// starter workbook in public/templates (Workbook tab: "what goes in it").
// Regenerate after changing a template; hand-edit wording if needed.

export type TemplateSheet = { sheet: string; what: string };

export const TEMPLATE_SHEETS: Record<string, TemplateSheet[]> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(resolve(ROOT, "src/lib/lessons/template-sheets.ts"), body);
console.log(`Wrote ${Object.keys(out).length} templates.`);
